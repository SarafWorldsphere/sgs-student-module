-- People who can sign in, and the one-time codes sent to their phone.
-- Replaces sgs_users_masters and sss_users_master.
-- The headmaster app reads username and role. The login app reads
-- login_id, email_id, mobile_no, and full_name. Both sets of columns are here.

CREATE TABLE roles (
    role_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    role_name   text NOT NULL,
    CONSTRAINT roles_tenant_id_role_id_key UNIQUE (tenant_id, role_id),
    CONSTRAINT roles_tenant_role_name_key UNIQUE (tenant_id, role_name)
);

CREATE TABLE users_masters (
    user_id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    login_id           text,
    username           text,
    password_hash      text,
    full_name          text,
    email_id           text,
    mobile_no          text,
    role_id            bigint,
    role               text,
    is_active          boolean NOT NULL DEFAULT true,
    created_datetime   timestamptz,
    modified_datetime  timestamptz,
    record_status      text,
    version_no         integer,
    CONSTRAINT users_masters_tenant_id_user_id_key UNIQUE (tenant_id, user_id),
    CONSTRAINT users_masters_role_fk
        FOREIGN KEY (tenant_id, role_id) REFERENCES roles (tenant_id, role_id),
    CONSTRAINT users_masters_login_id_not_blank
        CHECK (login_id IS NULL OR length(btrim(login_id)) > 0),
    CONSTRAINT users_masters_email_not_blank
        CHECK (email_id IS NULL OR length(btrim(email_id)) > 0)
);

CREATE UNIQUE INDEX users_masters_tenant_login_idx
    ON users_masters (tenant_id, login_id)
    WHERE login_id IS NOT NULL;

CREATE UNIQUE INDEX users_masters_tenant_email_idx
    ON users_masters (tenant_id, email_id)
    WHERE email_id IS NOT NULL;

CREATE INDEX users_masters_tenant_mobile_idx
    ON users_masters (tenant_id, mobile_no)
    WHERE mobile_no IS NOT NULL;

CREATE INDEX users_masters_tenant_role_idx
    ON users_masters (tenant_id, role);

CREATE INDEX users_masters_tenant_role_id_idx
    ON users_masters (tenant_id, role_id);

-- OTP rows are scoped by school, phone, and role. The old login table kept
-- one row per phone for the whole database.
CREATE TABLE otp_verifications (
    otp_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    phone       text NOT NULL,
    role        text NOT NULL,
    otp         text NOT NULL,
    expires_at  timestamptz NOT NULL,
    CONSTRAINT otp_verifications_tenant_id_otp_id_key UNIQUE (tenant_id, otp_id),
    CONSTRAINT otp_verifications_phone_role_key UNIQUE (tenant_id, phone, role)
);

CREATE INDEX otp_verifications_expires_at_idx
    ON otp_verifications (expires_at);
