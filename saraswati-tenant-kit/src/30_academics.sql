-- Classes, subjects, chapters, and exams.
-- Replaces sgs_class_master / sss_class_master and the matching subject,
-- chapter, chapter-content, and exam tables.
-- school_id from the old class and user tables is not copied. The school is tenant_id.

CREATE TABLE class_master (
    class_id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    class_name         text,
    section_name       text,
    academic_year      text,
    class_teacher_id   bigint,
    created_datetime   timestamptz,
    modified_datetime  timestamptz,
    record_status      text,
    version_no         integer,
    CONSTRAINT class_master_tenant_id_class_id_key UNIQUE (tenant_id, class_id),
    CONSTRAINT class_master_teacher_fk
        FOREIGN KEY (tenant_id, class_teacher_id)
        REFERENCES users_masters (tenant_id, user_id)
);

CREATE INDEX class_master_tenant_year_idx
    ON class_master (tenant_id, academic_year);

CREATE INDEX class_master_tenant_teacher_idx
    ON class_master (tenant_id, class_teacher_id);

CREATE TABLE subject_master (
    subject_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    class_id           bigint,
    subject_name       text,
    subject_code       text,
    teacher_id         bigint,
    created_datetime   timestamptz,
    modified_datetime  timestamptz,
    record_status      text,
    version_no         integer,
    CONSTRAINT subject_master_tenant_id_subject_id_key UNIQUE (tenant_id, subject_id),
    CONSTRAINT subject_master_class_fk
        FOREIGN KEY (tenant_id, class_id) REFERENCES class_master (tenant_id, class_id),
    CONSTRAINT subject_master_teacher_user_fk
        FOREIGN KEY (tenant_id, teacher_id) REFERENCES users_masters (tenant_id, user_id)
);

CREATE INDEX subject_master_tenant_class_idx
    ON subject_master (tenant_id, class_id);

CREATE INDEX subject_master_tenant_teacher_idx
    ON subject_master (tenant_id, teacher_id);

CREATE UNIQUE INDEX subject_master_tenant_class_code_idx
    ON subject_master (tenant_id, class_id, subject_code)
    WHERE subject_code IS NOT NULL AND class_id IS NOT NULL;

CREATE TABLE chapter_master (
    chapter_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    subject_id          bigint,
    chapter_no          integer,
    chapter_name        text,
    chapter_description text,
    chapter_order       integer,
    book_volume_number  text NOT NULL DEFAULT '1',
    created_datetime    timestamptz,
    created_user_id     text,
    modified_datetime   timestamptz,
    record_status       text,
    version_no          integer,
    CONSTRAINT chapter_master_tenant_id_chapter_id_key UNIQUE (tenant_id, chapter_id),
    CONSTRAINT chapter_master_subject_fk
        FOREIGN KEY (tenant_id, subject_id) REFERENCES subject_master (tenant_id, subject_id)
);

CREATE INDEX chapter_master_tenant_subject_order_idx
    ON chapter_master (tenant_id, subject_id, chapter_order);

CREATE TABLE chapter_content (
    chapter_content_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    chapter_id         bigint,
    subject_id         bigint,
    subject            text,
    lesson             text,
    content_title      text,
    chapter_name       text,
    full_text_content  text,
    pdf_url            text,
    is_active          boolean NOT NULL DEFAULT true,
    record_status      text,
    version_no         integer,
    created_datetime   timestamptz,
    updated_at         timestamptz,
    CONSTRAINT chapter_content_tenant_id_key UNIQUE (tenant_id, chapter_content_id),
    CONSTRAINT chapter_content_chapter_fk
        FOREIGN KEY (tenant_id, chapter_id) REFERENCES chapter_master (tenant_id, chapter_id),
    CONSTRAINT chapter_content_subject_fk
        FOREIGN KEY (tenant_id, subject_id) REFERENCES subject_master (tenant_id, subject_id)
);

CREATE INDEX chapter_content_tenant_chapter_idx
    ON chapter_content (tenant_id, chapter_id);

CREATE INDEX chapter_content_tenant_subject_idx
    ON chapter_content (tenant_id, subject_id);

CREATE INDEX chapter_content_tenant_subject_lesson_idx
    ON chapter_content (tenant_id, subject, lesson);

CREATE TABLE exam_master (
    exam_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    exam_name      text,
    exam_type      text,
    academic_year  text,
    record_status  text,
    CONSTRAINT exam_master_tenant_id_exam_id_key UNIQUE (tenant_id, exam_id)
);

CREATE INDEX exam_master_tenant_year_idx
    ON exam_master (tenant_id, academic_year);
