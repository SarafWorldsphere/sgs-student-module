-- File metadata and AI usage. file_url stores an s3://bucket/key URI.
-- New keys start with {tenant_id}/. The bucket stays private.

CREATE TABLE file_storage_metadata (
    file_id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id            uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    entity_type          text NOT NULL,
    entity_id            bigint NOT NULL,
    file_name            text NOT NULL,
    file_url             text NOT NULL,
    uploaded_by          bigint,
    created_at           timestamptz,
    created_user_id      text,
    created_ip_address   text,
    modified_datetime    timestamptz,
    modified_user_id     text,
    modified_ip_address  text,
    record_status        text,
    version_no           integer,
    updated_at           timestamptz,
    CONSTRAINT file_storage_metadata_tenant_id_key UNIQUE (tenant_id, file_id)
);

CREATE INDEX file_storage_metadata_tenant_entity_idx
    ON file_storage_metadata (tenant_id, entity_type, entity_id);

CREATE TABLE ai_usage_logs (
    ai_usage_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    client_name         text,
    user_email          text,
    module_name         text NOT NULL,
    feature_used        text NOT NULL,
    prompt_tokens       integer NOT NULL DEFAULT 0,
    completion_tokens   integer NOT NULL DEFAULT 0,
    total_tokens        integer NOT NULL DEFAULT 0,
    created_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ai_usage_logs_tenant_id_key UNIQUE (tenant_id, ai_usage_id),
    CONSTRAINT ai_usage_logs_token_check
        CHECK (
            prompt_tokens >= 0
            AND completion_tokens >= 0
            AND total_tokens >= 0
        )
);

CREATE INDEX ai_usage_logs_tenant_created_idx
    ON ai_usage_logs (tenant_id, created_at DESC);
