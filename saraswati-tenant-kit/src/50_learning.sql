CREATE TABLE student_learning_profiles (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id              uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    student_id             bigint NOT NULL,
    chapter_id             bigint NOT NULL,
    chapter_title          text NOT NULL,
    reading_time_minutes   integer NOT NULL,
    quiz_score             integer NOT NULL,
    retry_count            integer NOT NULL,
    comprehension_score    integer NOT NULL,
    reader_classification  text NOT NULL,
    generated_path         jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at             timestamptz NOT NULL DEFAULT now(),
    updated_at             timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT student_learning_profiles_tenant_id_key UNIQUE (tenant_id, id),
    CONSTRAINT student_learning_profiles_student_chapter_key
        UNIQUE (tenant_id, student_id, chapter_id),
    CONSTRAINT student_learning_profiles_student_fk
        FOREIGN KEY (tenant_id, student_id) REFERENCES student_master (tenant_id, student_id),
    CONSTRAINT student_learning_profiles_chapter_fk
        FOREIGN KEY (tenant_id, chapter_id) REFERENCES chapter_master (tenant_id, chapter_id),
    CONSTRAINT student_learning_profiles_reading_check
        CHECK (reading_time_minutes BETWEEN 0 AND 600),
    CONSTRAINT student_learning_profiles_quiz_check
        CHECK (quiz_score BETWEEN 0 AND 100),
    CONSTRAINT student_learning_profiles_retry_check
        CHECK (retry_count BETWEEN 0 AND 50),
    CONSTRAINT student_learning_profiles_comprehension_check
        CHECK (comprehension_score BETWEEN 0 AND 100),
    CONSTRAINT student_learning_profiles_reader_check
        CHECK (reader_classification IN ('Fast Reader', 'Average Reader', 'Slow Reader'))
);

CREATE INDEX student_learning_profiles_tenant_chapter_idx
    ON student_learning_profiles (tenant_id, chapter_id);

