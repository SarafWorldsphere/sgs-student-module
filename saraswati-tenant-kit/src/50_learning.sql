CREATE TABLE assessments (
    assessment_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    teacher_id       bigint NOT NULL,
    title            text NOT NULL,
