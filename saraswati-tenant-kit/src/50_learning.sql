    CONSTRAINT assignment_results_subject_fk
        FOREIGN KEY (tenant_id, subject_id) REFERENCES subject_master (tenant_id, subject_id)
);

CREATE INDEX assignment_results_tenant_student_idx
    ON assignment_results (tenant_id, student_id);

CREATE INDEX assignment_results_tenant_assignment_idx
    ON assignment_results (tenant_id, assignment_id);

CREATE INDEX assignment_results_tenant_subject_idx
    ON assignment_results (tenant_id, subject_id);

