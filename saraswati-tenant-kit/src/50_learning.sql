-- Assignments, quizzes, assessments, marks, and teacher-authored material.
-- assignment_results keeps the file bytes column the student app writes today.
-- New files belong in S3; file_storage_metadata holds the s3:// URI.

CREATE TABLE assignment_master (
    assignment_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id            uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    chapter_id           bigint,
    class_id             bigint,
    subject_id           bigint,
    assignment_title     text,
    assignment_text      text,
    due_date             date,
    assigned_by          bigint,
    created_datetime     timestamptz,
    created_user_id      text,
    created_ip_address   text,
    modified_datetime    timestamptz,
    modified_user_id     text,
    modified_ip_address  text,
    record_status        text,
    version_no           integer,
    CONSTRAINT assignment_master_tenant_id_key UNIQUE (tenant_id, assignment_id),
    CONSTRAINT assignment_master_chapter_fk
        FOREIGN KEY (tenant_id, chapter_id) REFERENCES chapter_master (tenant_id, chapter_id),
    CONSTRAINT assignment_master_class_fk
        FOREIGN KEY (tenant_id, class_id) REFERENCES class_master (tenant_id, class_id),
    CONSTRAINT assignment_master_subject_fk
        FOREIGN KEY (tenant_id, subject_id) REFERENCES subject_master (tenant_id, subject_id),
    CONSTRAINT assignment_master_assigned_by_fk
        FOREIGN KEY (tenant_id, assigned_by) REFERENCES users_masters (tenant_id, user_id)
);

CREATE INDEX assignment_master_tenant_class_idx
    ON assignment_master (tenant_id, class_id);

CREATE INDEX assignment_master_tenant_chapter_idx
    ON assignment_master (tenant_id, chapter_id);

CREATE INDEX assignment_master_tenant_subject_idx
    ON assignment_master (tenant_id, subject_id);

CREATE INDEX assignment_master_tenant_assigned_by_idx
    ON assignment_master (tenant_id, assigned_by);

CREATE INDEX assignment_master_tenant_due_idx
    ON assignment_master (tenant_id, due_date);

CREATE TABLE assignment_results (
    assignment_result_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id               uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    assignment_id           bigint,
    student_id              bigint NOT NULL,
    subject_id              bigint,
    class_name              text,
    assignment_title        text,
    due_date                date,
    status                  text,
    submitted_at            timestamptz,
    submitted_file_name     text,
    submitted_file_type     text,
