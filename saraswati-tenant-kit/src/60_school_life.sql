-- Notices, school events the headmaster dashboard lists, help articles,
-- and the parent communication tickets.

CREATE TABLE notice_board (
    notice_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    notice_title      text,
    notice_text       text,
    notice_date       date,
    applicable_class  text,
    posted_by         bigint,
    is_read           boolean NOT NULL DEFAULT false,
    created_datetime  timestamptz,
    modified_datetime timestamptz,
    record_status     text,
    version_no        integer,
    CONSTRAINT notice_board_tenant_id_key UNIQUE (tenant_id, notice_id),
    CONSTRAINT notice_board_posted_by_fk
        FOREIGN KEY (tenant_id, posted_by) REFERENCES users_masters (tenant_id, user_id)
);

CREATE INDEX notice_board_tenant_date_idx
    ON notice_board (tenant_id, notice_date DESC);

CREATE INDEX notice_board_tenant_unread_idx
    ON notice_board (tenant_id, is_read);

CREATE INDEX notice_board_tenant_posted_by_idx
    ON notice_board (tenant_id, posted_by);

CREATE TABLE function_master (
    function_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    function_name       text,
    function_date       date,
    coordinator_name    text,
    participants_count  integer,
    status              text,
    record_status       text,
    CONSTRAINT function_master_tenant_id_key UNIQUE (tenant_id, function_id)
);

CREATE INDEX function_master_tenant_date_idx
    ON function_master (tenant_id, function_date DESC);

CREATE TABLE tour_master (
    tour_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    tour_name        text,
    location_name    text,
    tour_date        date,
    incharge_name    text,
    students_count   integer,
    status           text,
    record_status    text,
    CONSTRAINT tour_master_tenant_id_key UNIQUE (tenant_id, tour_id)
);

CREATE INDEX tour_master_tenant_date_idx
    ON tour_master (tenant_id, tour_date DESC);

CREATE TABLE help_support (
    help_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    category       text,
    question       text,
    answer         text,
    support_email  text,
    support_phone  text,
    display_order  integer,
    is_active      boolean NOT NULL DEFAULT true,
    record_status  text,
    CONSTRAINT help_support_tenant_id_key UNIQUE (tenant_id, help_id)
);

CREATE INDEX help_support_tenant_order_idx
    ON help_support (tenant_id, display_order);

CREATE TABLE support_tickets (
    ticket_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    ticket_number   text NOT NULL,
    parent_id       bigint,
    student_id      bigint,
    subject         text,
    category        text,
    priority        text,
    status          text NOT NULL DEFAULT 'OPEN',
    recipient_name  text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT support_tickets_tenant_id_key UNIQUE (tenant_id, ticket_id),
    CONSTRAINT support_tickets_number_key UNIQUE (tenant_id, ticket_number),
    CONSTRAINT support_tickets_parent_fk
        FOREIGN KEY (tenant_id, parent_id) REFERENCES parent_master (tenant_id, parent_id),
    CONSTRAINT support_tickets_student_fk
        FOREIGN KEY (tenant_id, student_id) REFERENCES student_master (tenant_id, student_id)
);

CREATE INDEX support_tickets_tenant_parent_idx
    ON support_tickets (tenant_id, parent_id);

CREATE INDEX support_tickets_tenant_student_idx
    ON support_tickets (tenant_id, student_id);

CREATE TABLE ticket_messages (
    message_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    ticket_id    bigint NOT NULL,
    sender_type  text,
    sender_name  text,
    message      text,
    created_at   timestamptz NOT NULL DEFAULT now(),
    is_read      boolean NOT NULL DEFAULT false,
    CONSTRAINT ticket_messages_tenant_id_key UNIQUE (tenant_id, message_id),
    CONSTRAINT ticket_messages_ticket_fk
        FOREIGN KEY (tenant_id, ticket_id) REFERENCES support_tickets (tenant_id, ticket_id)
);

CREATE INDEX ticket_messages_tenant_ticket_idx
    ON ticket_messages (tenant_id, ticket_id);

CREATE TABLE student_notification_status (
    notification_status_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id              uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    student_id             bigint NOT NULL,
    notification_type      text NOT NULL,
    source_id              bigint NOT NULL,
    first_seen_at          timestamptz NOT NULL DEFAULT now(),
    read_at                timestamptz,
    CONSTRAINT student_notification_status_tenant_id_key
        UNIQUE (tenant_id, notification_status_id),
    CONSTRAINT student_notification_status_natural_key
        UNIQUE (tenant_id, student_id, notification_type, source_id),
    CONSTRAINT student_notification_status_student_fk
        FOREIGN KEY (tenant_id, student_id) REFERENCES student_master (tenant_id, student_id)
);

CREATE INDEX student_notification_status_tenant_unread_idx
    ON student_notification_status (tenant_id, student_id, read_at);
