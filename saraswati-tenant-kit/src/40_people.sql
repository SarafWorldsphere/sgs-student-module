-- Teachers, students, parents, and who teaches which class.
-- Student column names follow the SGS master (full_name, roll_no).
-- The SSS admin screen writes name and roll_number; those map to full_name and roll_no.
-- gender, class_name, and student_photo_key are the extra columns that admin writes.

CREATE TABLE teacher_master (
    teacher_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    full_name     text NOT NULL,
    email_id      text,
    phone         bigint,
    subject_name  text,
    class_id      bigint,
    section_1     text,
    section_2     text,
    role          text,
    is_active     boolean,
    created_at    timestamptz,
    CONSTRAINT teacher_master_tenant_id_teacher_id_key UNIQUE (tenant_id, teacher_id),
    CONSTRAINT teacher_master_class_fk
        FOREIGN KEY (tenant_id, class_id) REFERENCES class_master (tenant_id, class_id)
);

CREATE UNIQUE INDEX teacher_master_tenant_email_idx
    ON teacher_master (tenant_id, email_id)
    WHERE email_id IS NOT NULL;

CREATE INDEX teacher_master_tenant_class_idx
    ON teacher_master (tenant_id, class_id);

CREATE TABLE student_master (
    student_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    admission_no       text,
    full_name          text,
    gender             text,
    class_id           bigint,
    class_name         text,
    section            text,
    roll_no            text,
    student_phone      text,
    student_email      text,
    student_photo_key  text,
    guardian_name      text,
    guardian_phone     text,
    guardian_email     text,
    is_active          boolean,
    created_datetime   timestamptz,
    modified_datetime  timestamptz,
    created_at         timestamptz,
    updated_at         timestamptz,
    record_status      text,
    version_no         integer,
    CONSTRAINT student_master_tenant_id_student_id_key UNIQUE (tenant_id, student_id),
    CONSTRAINT student_master_class_fk
        FOREIGN KEY (tenant_id, class_id) REFERENCES class_master (tenant_id, class_id)
);

CREATE INDEX student_master_tenant_class_idx
    ON student_master (tenant_id, class_id);

CREATE UNIQUE INDEX student_master_tenant_email_idx
    ON student_master (tenant_id, student_email)
    WHERE student_email IS NOT NULL;

CREATE UNIQUE INDEX student_master_tenant_admission_idx
    ON student_master (tenant_id, admission_no)
    WHERE admission_no IS NOT NULL;

CREATE INDEX student_master_tenant_phone_idx
    ON student_master (tenant_id, student_phone)
    WHERE student_phone IS NOT NULL;

CREATE TABLE parent_master (
    parent_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    full_name      text,
    email          text,
    phone          text,
    profile_image  text,
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT parent_master_tenant_id_parent_id_key UNIQUE (tenant_id, parent_id)
);

CREATE UNIQUE INDEX parent_master_tenant_email_idx
    ON parent_master (tenant_id, email)
    WHERE email IS NOT NULL;

CREATE INDEX parent_master_tenant_phone_idx
    ON parent_master (tenant_id, phone)
    WHERE phone IS NOT NULL;

CREATE TABLE parent_student_map (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    parent_id          bigint NOT NULL,
    student_id         bigint NOT NULL,
    relationship_type  text NOT NULL,
    CONSTRAINT parent_student_map_tenant_id_key UNIQUE (tenant_id, id),
    CONSTRAINT parent_student_map_parent_fk
        FOREIGN KEY (tenant_id, parent_id) REFERENCES parent_master (tenant_id, parent_id),
    CONSTRAINT parent_student_map_student_fk
        FOREIGN KEY (tenant_id, student_id) REFERENCES student_master (tenant_id, student_id),
    CONSTRAINT parent_student_map_relationship_key
        UNIQUE (tenant_id, parent_id, student_id, relationship_type)
);

CREATE INDEX parent_student_map_tenant_student_idx
    ON parent_student_map (tenant_id, student_id);

CREATE TABLE teacher_class_subject_map (
    assignment_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    teacher_id        bigint NOT NULL,
    class_id          bigint NOT NULL,
    subject_name      text NOT NULL,
    academic_year     text NOT NULL,
    is_class_teacher  boolean NOT NULL DEFAULT false,
    is_active         boolean NOT NULL DEFAULT true,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT teacher_class_subject_map_tenant_id_key UNIQUE (tenant_id, assignment_id),
    CONSTRAINT teacher_class_subject_map_teacher_fk
        FOREIGN KEY (tenant_id, teacher_id) REFERENCES teacher_master (tenant_id, teacher_id),
    CONSTRAINT teacher_class_subject_map_class_fk
        FOREIGN KEY (tenant_id, class_id) REFERENCES class_master (tenant_id, class_id),
    CONSTRAINT teacher_class_subject_map_natural_key
        UNIQUE (tenant_id, teacher_id, class_id, subject_name, academic_year)
);

CREATE INDEX teacher_class_subject_map_tenant_class_idx
    ON teacher_class_subject_map (tenant_id, class_id);
